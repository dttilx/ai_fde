#!/bin/sh
set -eu
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=runtime_password="$APX_RUNTIME_PASSWORD" <<'SQL'
CREATE EXTENSION IF NOT EXISTS vector;
CREATE ROLE apx_runtime LOGIN PASSWORD :'runtime_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
GRANT CONNECT ON DATABASE apx240 TO apx_runtime;
GRANT USAGE ON SCHEMA public TO apx_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE apx_admin IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO apx_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE apx_admin IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO apx_runtime;
SQL
